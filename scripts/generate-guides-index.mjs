/**
 * Regenerates data/guides-index.generated.ts: a slug -> lazy dynamic-import map for
 * every rich guide data file under data/guides/*.ts.
 *
 * This is what lets app/(site)/guide/[slug]/page.tsx render a guide's full rich
 * content (products/faq/howToChoose/howWeEvaluated) WITHOUT that guide needing a
 * literal app/(site)/guide/<slug>/page.tsx route file - the dynamic route looks the
 * slug up in this map, dynamically imports just that one guide's data, and renders it
 * via components/guide/RichGuidePage.tsx. Turbopack code-splits each entry into its
 * own chunk, so only the requested guide's data is ever loaded per request.
 *
 * Must be re-run (and the output committed) any time a data/guides/<slug>.ts file is
 * added or removed - run it as part of every batch pipeline, alongside
 * append-guides-registry-*.mjs.
 *
 * Usage: node scripts/generate-guides-index.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const GUIDES_DIR = resolve(ROOT, "data", "guides");
const LITERAL_ROUTE_DIR = resolve(ROOT, "app", "(site)", "guide");

// Same compatibility check as scripts/generate-guide-page.mjs: legacy guide data files
// (predating the 2026-07-18 template revision) don't export products/howWeEvaluated/
// howToChoose/buyingCriteria in the shape RichGuidePage expects - some use entirely
// different per-guide product interfaces (FileCabinet, Monitor27Under200, etc.) or no
// products export at all. Only include files that already match the modern shape.
const REQUIRED_EXPORTS = ["products", "howWeEvaluated", "howToChoose", "buyingCriteria"];

const allSlugs = readdirSync(GUIDES_DIR)
  .filter((f) => f.endsWith(".ts"))
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const slugs = [];
const skipped = [];
for (const slug of allSlugs) {
  const content = readFileSync(resolve(GUIDES_DIR, `${slug}.ts`), "utf8");
  const missing = REQUIRED_EXPORTS.filter((name) => !new RegExp(`export const ${name}\\b`).test(content));
  if (missing.length > 0) {
    skipped.push(slug);
  } else {
    slugs.push(slug);
  }
}

const entries = slugs
  .map((slug) => `  ${JSON.stringify(slug)}: () => import("./guides/${slug}"),`)
  .join("\n");

// Slugs with a hand-authored static route at app/(site)/guide/<slug>/page.tsx whose
// content isn't covered by guideDataLoaders above. Computed here at build time and
// committed as a plain array, rather than scanned from the filesystem at request time
// (lib/migrated-silos.ts used to do this via fs.readdirSync in a Server Component) -
// a serverless deployment's function bundle doesn't reliably include the full app/
// source tree, so that runtime scan could return an incomplete/inconsistent result per
// invocation and produce a redirect loop between a silo URL and /guide/<slug>.
const literalRouteSlugs = readdirSync(LITERAL_ROUTE_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("[") && !d.name.startsWith("("))
  .map((d) => d.name)
  .sort();
const slugSet = new Set(slugs);
const legacyLiteralRouteSlugs = literalRouteSlugs.filter((s) => !slugSet.has(s));

const legacyEntries = legacyLiteralRouteSlugs.map((s) => `  ${JSON.stringify(s)},`).join("\n");

const content = `// AUTO-GENERATED by scripts/generate-guides-index.mjs - do not hand-edit.
// Re-run that script after adding or removing any data/guides/<slug>.ts file, or any
// app/(site)/guide/<slug>/page.tsx literal route directory.
import type { GuideProduct, HowToChooseSection } from "@/components/guide/RichGuidePage";

export interface GuideDataModule {
  guideTitle: string;
  metaTitle: string;
  metaDescription: string;
  mainKeyword?: string;
  introParagraphs?: string[];
  lastUpdated: string;
  readTime: string;
  heroImage: string;
  products: GuideProduct[];
  howWeEvaluated?: { title: string; description: string }[];
  howToChoose?: HowToChooseSection[];
  buyingCriteria?: { criterion: string; explanation: string }[];
  faq?: { q: string; a: string }[];
  relatedGuides?: { href: string; title: string }[];
}

export const guideDataLoaders: Record<string, () => Promise<GuideDataModule>> = {
${entries}
};

// Slugs whose full content only exists in a hand-authored app/(site)/guide/<slug>/
// page.tsx route (not covered by guideDataLoaders above). A silo detail page must
// redirect back to /guide/<slug> for these rather than render GuideDetail's thin
// registry stub, or it silently serves an emptied-out page.
export const legacyLiteralRouteSlugs: string[] = [
${legacyEntries}
];
`;

writeFileSync(resolve(ROOT, "data", "guides-index.generated.ts"), content, "utf8");
console.log(`Wrote data/guides-index.generated.ts with ${slugs.length} entries (${skipped.length} legacy files skipped, incompatible shape), ${legacyLiteralRouteSlugs.length} legacy literal-route slugs.`);
